# offline/semantic_gen/schemas.py

from pydantic import BaseModel, Field


# One foreign key found by the LLM (relationships.py)
class FKRelation(BaseModel):
    from_column: str = Field(description="Referencing column as table.column, e.g. booking.passenger_id")
    to_column:   str = Field(description="Referenced identifier column as table.column, e.g. passenger.passenger_id")


# Output of the infer_fk_relations step (relationships.py): the list of FKRelation
class FKRelations(BaseModel):
    relations: list[FKRelation] = Field(description="List of foreign key relationships between tables.")

# One column description generated by the LLM (tables.py)
class ColumnSemantics(BaseModel):
    name:        str  = Field(description="Column name, spelled exactly as in the DDL")
    description: str  = Field(description="Business meaning of the column, in one short sentence")
    unclear:     bool = Field(description="True if its meaning, or a unit that matters, cannot be told from its name and sample values")
    categorical: bool = Field(description="True if the column holds labels from a closed set a user would filter on (country, status, fare class)")


# Output of the semantics step (tables.py): one table and its columns
class TableSemantics(BaseModel):
    description: str                   = Field(description="What one row of the table represents")
    columns:     list[ColumnSemantics] = Field(description="Description of every column of the table")

# One business metric proposed by the LLM (metrics.py)
class MetricProposal(BaseModel):
    name:           str       = Field(description="snake_case name of the metric, e.g. revenue, order_count")
    description:    str       = Field(description="What the metric measures, in one sentence, including what it includes or excludes")
    synonyms:       list[str] = Field(description="Other words users may use for it, in English and in the other languages users may ask in")
    expr:           str       = Field(description="Aggregate SQL expression, every column written table.column")
    time_dimension: str       = Field(description="Default date column for periods and trends, as table.column, or empty if none applies")
    dimensions:     list[str] = Field(default_factory=list, description="Entities the metric can be broken down by: singular business names backed by an identifier of the fact table or of a table it joins to, reusing the DIMENSIONS IN USE words. Empty when unsure.")


# Output of the metrics step (metrics.py): the proposed metrics
class MetricProposals(BaseModel):
    metrics: list[MetricProposal] = Field(description="Business metrics analysts would ask about, at most 8")
