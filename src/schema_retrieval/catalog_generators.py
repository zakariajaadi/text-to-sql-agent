# src/schema_retrieval/catalog_generators.py

"""
Offline LLM generators for the reviewed configuration files read by the indexer.

    generate_semantics  → config/semantics/<db>.yaml   (descriptions and categorical columns)
    infer_fk_relations  → config/fk_relations.yaml     (FK relations, for Hive / Impala)
    describe_db         → config/db_descriptions.yaml  (database description)

All three are additive: they only fill what is missing and never overwrite reviewed
content. They read the database directly (DDL + existing semantics), never Chroma,
so they can run before the first index.

The values of the categorical columns are not generated here: they are data, read
from the database at index time (lib/categorical_values.py).

Pipeline order: semantics → fk-relations → (review) → index → describe
Run through the schema_indexer CLI (see schema_indexer.py).
"""

from concurrent.futures import ThreadPoolExecutor

import yaml
from langchain_community.utilities import SQLDatabase
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from loguru import logger
from omegaconf import OmegaConf
from sqlalchemy import inspect as sa_inspect

from config import BASE_DIR, cfg, fast_model, load_fk_relations, model
from lib.semantics import SEMANTICS_DIR, load_semantics, render_table
from schema_retrieval.prompts import (
    DB_DESCRIPTION_PROMPT,
    FK_RELATIONS_PROMPT,
    TABLE_SEMANTICS_PROMPT,
)
from schema_retrieval.schemas import FKRelations, TableSemantics

# ------------------------------------------------------------
# Constants
# ------------------------------------------------------------

FK_RELATIONS_PATH    = BASE_DIR / "config" / "fk_relations.yaml"
DB_DESCRIPTIONS_PATH = BASE_DIR / "config" / "db_descriptions.yaml"

SEMANTICS_HEADER = """\
# Semantic layer, generated (schema_indexer semantics) and reviewed manually.
# The generator only ADDS missing content, it never overwrites reviewed content.
#   description, columns : business meaning of the table and of each column
#   categorical_columns  : columns holding a closed set of labels (country, status...),
#                          whose values are read from the database at index time.
#                          Remove a column from the list to reject it: it won't come back
#   read_mode, key_columns, partition_column, version_column : Hive table layout

"""

# Key order of a table block in the YAML (unknown keys last)
SEMANTICS_KEY_ORDER = [
    "description", "read_mode", "key_columns", "partition_column", "version_column",
    "categorical_columns", "columns",
]

FK_RELATIONS_HEADER = """\
# Declarative FK relations, for engines that expose no FK metadata (Hive, Impala).
# Generated by LLM (schema_indexer fk-relations), then reviewed manually:
#   - the generator only ADDS relations, never modifies or removes existing ones
#   - to reject a generated relation, move it to `ignore` (otherwise it comes back)
# Table and column names must match the engine (lowercase for Hive).

"""

# ------------------------------------------------------------
# Chains
# ------------------------------------------------------------

# One table DDL → its table and column descriptions
semantics_chain = (
    ChatPromptTemplate.from_messages([("human", TABLE_SEMANTICS_PROMPT)])
    | fast_model.with_structured_output(TableSemantics)
)

# All schemas → FK relations between tables
fk_relations_chain = (
    ChatPromptTemplate.from_messages([("human", FK_RELATIONS_PROMPT)])
    | model.with_structured_output(FKRelations)
)

# All schemas → database-level description
db_description_chain = (
    ChatPromptTemplate.from_messages([("human", DB_DESCRIPTION_PROMPT)])
    | fast_model
    | StrOutputParser()
)

# ------------------------------------------------------------
# Generator functions
# ------------------------------------------------------------

def generate_semantics(db_name: str):
    """
    Generates a semantic layer via LLM into config/semantics/<db>.yaml: missing table
    and column descriptions, and which columns are categorical.

    Compares current DB tables and columns against `config/semantics/<db>.yaml`.
    Only missing tables, tables with undocumented columns, or tables without
    `categorical_columns` are routed to the LLM.

    Additive only:
    existing descriptions are never overwritten, and a reviewed `categorical_columns`
    list only gains columns that are new to the table.
    """
    db         = _connect(db_name)
    existing   = load_semantics(db_name)
    columns    = _table_columns(db)
    all_tables = ", ".join(columns)

    # 1. Only tables with something missing go to the LLM
    todo = [
        t for t in columns
        if t not in existing
        or "categorical_columns" not in existing[t]
        or set(columns[t]) - set(existing[t].get("columns") or {})
    ]

    def generate(table: str) -> tuple[str, TableSemantics]:
        ddl = db.get_table_info(table_names=[table]).strip()
        logger.info(f"[{db_name}] Describing: {table}")
        return table, semantics_chain.invoke({
            "db_name":    db_name,
            "all_tables": all_tables,
            "ddl":        ddl,
        })

    # 2. Generate descriptions in parallel
    # (max_workers stays under the SQLAlchemy pool size: 5 + 10 overflow)
    with ThreadPoolExecutor(max_workers=8) as executor:
        generated = dict(executor.map(generate, todo))

    # 3. Merge — fill only what is missing
    added = 0
    for table, result in generated.items():
        entry = existing.setdefault(table, {})
        entry.setdefault("description", result.description)
        entry["columns"] = entry.get("columns") or {}

        # Categorical columns, in DDL order (columns the LLM invented are dropped).
        # A reviewed list only gains the columns new to the table: rejections stay rejected
        flagged     = {c.name for c in result.columns if c.categorical}
        new_columns = [c for c in columns[table] if c not in entry["columns"]]
        if "categorical_columns" not in entry:
            entry["categorical_columns"] = [c for c in columns[table] if c in flagged]
        else:
            entry["categorical_columns"] += [c for c in new_columns if c in flagged]

        described = {c.name: c.description for c in result.columns}
        for column in new_columns:
            if column in described:
                entry["columns"][column] = described[column]
                added += 1

    # Flag descriptions of columns that no longer exist
    for table, entry in existing.items():
        for column in entry.get("columns") or {}:
            if column not in columns.get(table, []):
                logger.warning(f"[{db_name}] Stale description: {table}.{column} no longer exists")

    SEMANTICS_DIR.mkdir(parents=True, exist_ok=True)
    path = SEMANTICS_DIR / f"{db_name}.yaml"
    path.write_text(_dump_semantics(existing))

    logger.info(f"[{db_name}] {len(todo)} table(s) described, {added} column description(s) added — review them.")


def infer_fk_relations(db_name: str):
    """
    Infers Foreign Key relations via LLM and merges them into config/fk_relations.yaml.

    Meant for engines that expose no FK metadata (Hive, Impala).
    Relations pointing to unknown tables or columns are dropped.

    Additive only: existing and ignored relations are never modified.
    """
    db = _connect(db_name)

    # 1. Infer relations from the schemas (DDL + reviewed semantics)
    inferred = fk_relations_chain.invoke({
        "db_name": db_name,
        "schemas": _render_schemas(db, db_name),
    }).relations

    # 2. Drop relations referencing unknown tables or columns (LLM hallucinations)
    columns = _table_columns(db)

    def exists(ref: str) -> bool:
        table, _, column = ref.partition(".")
        return column in columns.get(table, [])

    valid = []
    for r in inferred:
        if exists(r.from_column) and exists(r.to_column):
            valid.append({"from": r.from_column, "to": r.to_column})
        else:
            logger.warning(f"[{db_name}] Rejected unknown relation: {r.from_column} -> {r.to_column}")

    # 3. Merge — only add relations neither declared nor ignored
    path  = FK_RELATIONS_PATH
    data  = (yaml.safe_load(path.read_text()) if path.exists() else None) or {}
    entry = data.setdefault(db_name, {})
    entry.setdefault("relations", [])
    entry.setdefault("ignore", [])

    known = {(r["from"], r["to"]) for r in entry["relations"] + entry["ignore"]}
    added = [r for r in valid if (r["from"], r["to"]) not in known]
    entry["relations"].extend(added)

    path.write_text(
        FK_RELATIONS_HEADER
        + yaml.safe_dump(data, sort_keys=False, default_flow_style=None, allow_unicode=True)
    )
    logger.info(f"[{db_name}] {len(added)} new relation(s) added to {path.name} — review them.")


def describe_db(db_name: str):
    """
    Generate a database-level description into db_descriptions.yaml.
    Additive only: an existing description is never overwritten (delete it to regenerate).
    """
    path     = DB_DESCRIPTIONS_PATH
    existing = OmegaConf.load(path) if path.exists() else OmegaConf.create()

    # Keep reviewed descriptions — the LLM only fills missing databases
    if db_name in existing:
        logger.info(f"[{db_name}] Description already exists in {path.name} — skipped.")
        return

    db          = _connect(db_name)
    description = db_description_chain.invoke({
        "db_name": db_name,
        "schemas": _render_schemas(db, db_name),
    }).strip()

    existing[db_name] = description
    OmegaConf.save(existing, path)

    logger.info(f"[{db_name}] Database description written to {path.name} — review it.")


# ------------------------------------------------------------
# helpers
# ------------------------------------------------------------

def _connect(db_name: str) -> SQLDatabase:
    return SQLDatabase.from_uri(cfg.get_db(db_name).uri)


def _table_columns(db: SQLDatabase) -> dict[str, list[str]]:
    """Current columns of each table, in DDL order."""
    inspector = sa_inspect(db._engine)
    return {t: [c["name"] for c in inspector.get_columns(t)] for t in db.get_usable_table_names()}


def _render_schemas(db: SQLDatabase, db_name: str) -> str:
    """All tables as one string: rendered with semantics when documented, raw DDL otherwise."""
    semantics    = load_semantics(db_name)
    fk_relations = load_fk_relations(db_name)

    schemas = []
    for table in db.get_usable_table_names():
        ddl = db.get_table_info(table_names=[table]).strip()
        schemas.append(render_table(table, ddl, semantics[table], fk_relations) if table in semantics else ddl)
    return "\n\n".join(schemas)


class _SemanticsDumper(yaml.SafeDumper):
    """Lists on one line ([a, b, c]): key_columns and value lists stay compact for review."""


_SemanticsDumper.add_representer(
    list, lambda dumper, data: dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=True)
)


def _dump_semantics(semantics: dict) -> str:
    """Dump one YAML block per table, separated by a blank line for readability."""
    def ordered(entry: dict) -> dict:
        rank = {key: i for i, key in enumerate(SEMANTICS_KEY_ORDER)}
        return dict(sorted(entry.items(), key=lambda item: rank.get(item[0], len(rank))))

    return SEMANTICS_HEADER + "\n".join(
        yaml.dump({table: ordered(entry)}, Dumper=_SemanticsDumper, sort_keys=False, allow_unicode=True, width=1000)
        for table, entry in semantics.items()
    )
