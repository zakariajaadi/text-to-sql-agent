# src/schema_retrieval/schema_indexer.py

"""
Two-step process:
    1. index    — DB → enriched DDL via LLM → Chroma 
    2. describe — Chroma schemas → database-level description → db_descriptions.yaml

CLI usage:
    # Full pipeline (index + describe) for all databases
    python -m schema_retrieval.schema_indexer

    # Full pipeline for a specific database only
    python -m schema_retrieval.schema_indexer --db Chinook

    # Run describe step only
    python -m schema_retrieval.schema_indexer describe --db Northwind

    # Run relations step only
    python -m schema_retrieval.schema_indexer fk-relations --db Chinook
"""

import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml
from langchain_community.utilities import SQLDatabase
from langchain_core.documents import Document
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from loguru import logger
from omegaconf import OmegaConf
from sqlalchemy import inspect as sa_inspect

from config import BASE_DIR, cfg, embedding_model, load_fk_relations
from schema_retrieval.indexer_prompts import (
    DB_DESCRIPTION_PROMPT,
    FK_RELATIONS_PROMPT,
    SCHEMA_DESCRIPTION_PROMPT,
    TABLE_SEMANTICS_PROMPT,
)
from schema_retrieval.indexer_schemas import FKRelation, FKRelations, TableSemantics
from schema_retrieval.vector_store import VectorStoreManager

FK_RELATIONS_HEADER = """\
# Declarative FK relations, for engines that expose no FK metadata (Hive, Impala).
# Generated by LLM (schema_indexer relations), then reviewed manually:
#   - the generator only ADDS relations, never modifies or removes existing ones
#   - to reject a generated relation, move it to `ignore` (otherwise it comes back)
# Table and column names must match the engine (lowercase for Hive).

"""
SEMANTICS_DIR = BASE_DIR / "config" / "semantics" # Directory where semantics files are saved

class SchemaIndexer:
    """
    Extracts and indexes the DDL schemas of a single database.

    Each table is extracted as a separate .sql file, then embedded
    into the shared Chroma store with its database name in metadata.
    This allows the retriever to filter by database at query time
    without maintaining separate vector stores per database.

    Attributes:
        db:          SQLDatabase connection for the target database.
        db_name:     Name of the target database (e.g. "Chinook").
        schemas_dir: Directory where extracted .sql files are saved.
        vsm:         VectorStoreManager pointing to the shared Chroma store.
    """

    def __init__(self, db_name: str):
        """
        Args:
            db_name: Name of the database to index. Must match an entry
                     in config.yaml databases[].name.
        """
        db_cfg = cfg.get_db(db_name)

        self.db          = SQLDatabase.from_uri(db_cfg.uri)
        self.db_name     = db_name
        self.schemas_dir = Path(cfg.retrieval.schemas_directory) / db_name

        # Single shared Chroma store — same persist_directory for all databases
        self.vsm = VectorStoreManager(
            embedding_model=embedding_model,
            persist_directory=cfg.retrieval.persist_directory,
        )

    def extract(self) -> list[Document]:
        """
        Build one document per table, in parallel.
        Tables documented in config/semantics/<db>.yaml are rendered without LLM;
        the others fall back to LLM enrichment.
        """
        tables         = self.db.get_usable_table_names()
        all_tables_str = ", ".join(tables)
        semantics      = self._load_semantics()
        fk_relations      = load_fk_relations(self.db_name)

        def enrich_table(table: str) -> Document:
            # Get table DDL
            ddl = self.db.get_table_info(table_names=[table]).strip()

            # Reviewed semantics take precedence over LLM enrichment
            if table in semantics:
                enriched, source = self._render_semantics(table, ddl, semantics[table], fk_relations), "semantics"
            else:
                enriched, source = self._enrich_chain(ddl, all_tables_str), "llm"

            logger.info(f"[{self.db_name}] Extracted: {table} ({source})")
            return Document(
                page_content=enriched,
                metadata={"table_name": table, "db_name": self.db_name},
            )

        # Parallel execution of enrich table
        with ThreadPoolExecutor() as executor:
            documents = list(executor.map(enrich_table, tables))

        return documents


    def index(self, documents: list[Document]):
        """
        Embed documents into the shared Chroma store with deterministic IDs.

        Deduplication strategy: delete-then-add with deterministic IDs.
            - IDs are built as "<db_name>_<table_name>"
            - delete() is a no-op on unknown IDs, so the first run is safe.
        """
        store = self.vsm.get_store()

        # Build deterministic IDs
        ids = [
            f"{doc.metadata['db_name']}_{doc.metadata['table_name']}"
            for doc in documents
        ]

        # Index documents with dedup
        store.delete(ids=ids)
        store.add_documents(documents, ids=ids)

        logger.info(f"[{self.db_name}] Indexed {len(documents)} schemas to Chroma.")

    def describe(self):
        """
        Generate a database-level description from Chroma schemas into db_descriptions.yaml.
        Additive only: an existing description is never overwritten (delete it to regenerate).
        """
        desc_path = BASE_DIR / "config" / "db_descriptions.yaml"
        existing  = OmegaConf.load(desc_path) if desc_path.exists() else OmegaConf.create()

        # Keep reviewed descriptions — the LLM only fills missing databases
        if self.db_name in existing:
            logger.info(f"[{self.db_name}] Description already exists in {desc_path.name} — skipped.")
            return

        # Load schemas from Chroma
        docs        = self.vsm.get_store().get(where={"db_name": {"$eq": self.db_name}})
        all_schemas = "\n\n".join(docs["documents"])

        # Describe database
        description = self._describe_chain(all_schemas)

        # Save description
        existing[self.db_name] = description
        OmegaConf.save(existing, desc_path)

        logger.info(f"[{self.db_name}] Database description written to {desc_path.name} — review it.")
    
    def infer_fk_relations(self):
        """
        Infer FK relations with the LLM and merge them into config/fk_relations.yaml.
        Additive only: existing and ignored relations are never modified.
        """
        
        # 1. Infer relations from the enriched schemas stored in Chroma
        docs        = self.vsm.get_store().get(where={"db_name": {"$eq": self.db_name}}) # DDL documents
        all_schemas = "\n\n".join(docs["documents"]) # All schemas as a single string
        inferred    = self._infer_fk_relations_chain(all_schemas)

        # 2. Drop relations referencing unknown tables or columns (LLM hallucinations)
        inspector = sa_inspect(self.db._engine)
        columns   = {
            table: {c["name"] for c in inspector.get_columns(table)}
            for table in self.db.get_usable_table_names()
        }

        def exists(ref: str) -> bool:
            table, _, column = ref.partition(".")
            return column in columns.get(table, set())

        valid = []
        for r in inferred:
            if exists(r.from_column) and exists(r.to_column):
                valid.append({"from": r.from_column, "to": r.to_column})
            else:
                logger.warning(f"[{self.db_name}] Rejected unknown relation: {r.from_column} -> {r.to_column}")

        # 3. Merge — only add relations neither declared nor ignored
        path  = BASE_DIR / "config" / "fk_relations.yaml"
        data  = (yaml.safe_load(path.read_text()) if path.exists() else None) or {}
        entry = data.setdefault(self.db_name, {})
        entry.setdefault("relations", [])
        entry.setdefault("ignore", [])

        known = {(r["from"], r["to"]) for r in entry["relations"] + entry["ignore"]}
        added = [r for r in valid if (r["from"], r["to"]) not in known]
        entry["relations"].extend(added)
        
        path.write_text(
            FK_RELATIONS_HEADER
            + yaml.safe_dump(data, sort_keys=False, default_flow_style=None, allow_unicode=True)
        )
        logger.info(f"[{self.db_name}] {len(added)} new relation(s) added to {path.name} — review them.")
    
    def semantics(self):
        """
        Generate table and column descriptions with the LLM into config/semantics/<db>.yaml.
        Additive only: existing descriptions are never overwritten.
        """
        existing   = self._load_semantics()
        tables     = self.db.get_usable_table_names()
        all_tables = ", ".join(tables)

        # Current columns of each table, in DDL order
        inspector = sa_inspect(self.db._engine)
        columns   = {t: [c["name"] for c in inspector.get_columns(t)] for t in tables}

        # 1. Only tables that are missing or have undocumented columns go to the LLM
        todo = [
            t for t in tables
            if t not in existing or set(columns[t]) - set(existing[t].get("columns") or {})
        ]

        def generate(table: str) -> tuple[str, TableSemantics]:
            ddl = self.db.get_table_info(table_names=[table]).strip()
            logger.info(f"[{self.db_name}] Describing: {table}")
            return table, self._infer_semantics(ddl, all_tables)

        # 2. Generate descriptions in parallel
        with ThreadPoolExecutor() as executor:
            generated = dict(executor.map(generate, todo))

        # 3. Merge — fill only what is missing
        added = 0
        for table, result in generated.items():
            entry = existing.setdefault(table, {})
            entry.setdefault("description", result.description)
            entry["columns"] = entry.get("columns") or {}

            described = {c.name: c.description for c in result.columns}
            for column in columns[table]:
                if column not in entry["columns"] and column in described:
                    entry["columns"][column] = described[column]
                    added += 1

        # Flag descriptions of columns that no longer exist
        for table, entry in existing.items():
            for column in entry.get("columns") or {}:
                if column not in columns.get(table, []):
                    logger.warning(f"[{self.db_name}] Stale description: {table}.{column} no longer exists")

        SEMANTICS_DIR.mkdir(parents=True, exist_ok=True)
        path = SEMANTICS_DIR / f"{self.db_name}.yaml"
        path.write_text(self._dump_semantics(existing))

        logger.info(f"[{self.db_name}] {len(todo)} table(s) described, {added} column description(s) added — review them.")

    def run(self):
        """Run the full pipeline: extract → index → describe."""
        documents = self.extract()
        self.index(documents)
    
    # ------------------------------------------------------------
    # helper methods: Chains
    # ------------------------------------------------------------

    def _enrich_chain(self, ddl: str, all_tables: str) -> str:
        from config import fast_model
         
        # Build chain
        prompt = ChatPromptTemplate.from_messages([
            ("human", SCHEMA_DESCRIPTION_PROMPT),
        ])  
        chain = prompt | fast_model | StrOutputParser()
        
        # return enrichement 
        return chain.invoke({
            "db_name":    self.db_name,
            "all_tables": all_tables,
            "ddl":        ddl,
        })


    def _describe_chain(self, all_schemas: str) -> str:
        from config import fast_model

        # Build chain
        prompt = ChatPromptTemplate.from_messages([
            ("human", DB_DESCRIPTION_PROMPT),
        ])
        chain = prompt | fast_model | StrOutputParser()

        # return database description
        return chain.invoke({
            "db_name": self.db_name,
            "schemas": all_schemas,
        }).strip()

    def _infer_fk_relations_chain(self, schemas: str) -> list[FKRelation]:
        from config import model

        # Build chain
        prompt = ChatPromptTemplate.from_messages([
            ("human", FK_RELATIONS_PROMPT),
        ])
        chain = prompt | model.with_structured_output(FKRelations)

        # return inferred relations
        return chain.invoke({
            "db_name": self.db_name,
            "schemas": schemas,
        }).relations

    def _infer_semantics(self, ddl: str, all_tables: str) -> TableSemantics:
        from config import fast_model

        # Build chain
        prompt = ChatPromptTemplate.from_messages([
            ("human", TABLE_SEMANTICS_PROMPT),
        ])
        chain = prompt | fast_model.with_structured_output(TableSemantics)

        # return table and column descriptions
        return chain.invoke({
            "db_name":    self.db_name,
            "all_tables": all_tables,
            "ddl":        ddl,
        })
    
    def _load_semantics(self) -> dict:
        path = SEMANTICS_DIR / f"{self.db_name}.yaml"
        return (yaml.safe_load(path.read_text()) if path.exists() else None) or {}

    def _render_semantics(self, table: str, ddl: str, semantics: dict,
                          fk_relations: list[tuple[str, str]]) -> str:
        """Build the indexed document from the DDL and reviewed semantics and FK relations — no LLM."""
        columns = semantics.get("columns", {})
        lines   = [f"-- Table: {table}", f"-- Description: {semantics['description']}"]

        # Join conditions involving this table, from fk_relations.yaml
        joins = [
            f"{source} = {target}"
            for source, target in fk_relations
            if table in (source.split(".")[0], target.split(".")[0])
        ]
        if joins:
            lines.append(f"-- Joins: {', '.join(joins)}")
        lines.append("")

        # Append each column description as an inline SQL comment
        in_create = False
        for line in ddl.splitlines():
            if line.startswith("CREATE TABLE"):
                in_create = True
            elif line.startswith(")"):
                in_create = False
            elif in_create:
                name = line.strip().split()[0].strip('`"[]')
                if name in columns:
                    line = f"{line.rstrip()}  -- {columns[name]}"
            lines.append(line)

        return "\n".join(lines)    
    
    @staticmethod
    def _dump_semantics(semantics: dict) -> str:
        """Dump one YAML block per table, separated by a blank line for readability."""
        return "\n".join(
            yaml.safe_dump({table: entry}, sort_keys=False, allow_unicode=True, width=1000)
            for table, entry in semantics.items()
        )

# =============================================================================
# CLI entry point
# =============================================================================

def main():
    """
    CLI entry point supporting optional --db flag and command selection.

    Examples:
        python -m schema_retrieval.schema_indexer              # all dbs, full pipeline
        python -m schema_retrieval.schema_indexer --db Chinook # one db, full pipeline
        python -m schema_retrieval.schema_indexer describe --db Northwind
        python -m schema_retrieval.schema_indexer fk-relations --db Chinook
    """
    args    = sys.argv[1:]
    command = "all"
    db_name = None

    if "--db" in args:
        idx     = args.index("--db")
        db_name = args[idx + 1]
        args    = [a for i, a in enumerate(args) if i not in (idx, idx + 1)]

    if args:
        command = args[0]

    targets = (
        [cfg.get_db(db_name).name]
        if db_name
        else [db.name for db in cfg.databases]
    )

    for name in targets:
        indexer = SchemaIndexer(name)
        if command == "describe":
            indexer.describe()
        elif command == "fk-relations":
            indexer.infer_fk_relations()
        elif command == "semantics":
            indexer.semantics()
        else:
            indexer.run()


if __name__ == "__main__":
    main()
