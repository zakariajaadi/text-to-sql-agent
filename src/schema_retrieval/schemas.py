from pydantic import BaseModel, Field


# One foreign key found by the LLM (catalog_generators.py)
class FKRelation(BaseModel):
    from_column: str = Field(description="Referencing column as table.column, e.g. booking.passenger_id")
    to_column:   str = Field(description="Referenced identifier column as table.column, e.g. passenger.passenger_id")


# Output of the infer_fk_relations step (catalog_generators.py): the list of FKRelation
class FKRelations(BaseModel):
    relations: list[FKRelation] = Field(description="List of foreign key relationships between tables.")

# One column description generated by the LLM (catalog_generators.py)
class ColumnSemantics(BaseModel):
    name:        str  = Field(description="Column name, spelled exactly as in the DDL")
    description: str  = Field(description="Business meaning of the column, in one short sentence")
    categorical: bool = Field(description="True if the column holds labels from a closed set a user would filter on (country, status, fare class)")


# Output of the semantics step (catalog_generators.py): one table and its columns
class TableSemantics(BaseModel):
    description: str                   = Field(description="What one row of the table represents")
    columns:     list[ColumnSemantics] = Field(description="Description of every column of the table")